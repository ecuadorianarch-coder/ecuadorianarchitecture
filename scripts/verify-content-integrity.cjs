/**
 * Ecuadorian Architecture — Pre-Build Content Integrity Sentinel
 * Guarantees zero synthetic, draft, or unapproved test projects ever enter production.
 */
const fs = require('fs');
const path = require('path');

const dataDir = path.join(__dirname, '..', 'src', 'data');
const projectsFile = path.join(dataDir, 'projects.json');

console.log('🛡️ [SENTINEL] Verifying content integrity in projects.json...');

if (!fs.existsSync(projectsFile)) {
  console.error('❌ [SENTINEL FATAL]: projects.json does not exist!');
  process.exit(1);
}

const projects = JSON.parse(fs.readFileSync(projectsFile, 'utf-8') || '[]');

const issues = [];

projects.forEach((proj, idx) => {
  const title = proj.title || 'Untitled';
  
  // 1. Guard against non-published statuses in canonical catalog
  if (proj.status && proj.status !== 'published') {
    issues.push(`Project #${idx} "${title}" has illegal non-published status: "${proj.status}". Drafts must stay in editorialOffice.json.`);
  }

  // 2. Guard against test/dummy autogenerated slugs
  if (/-mw3[a-z0-9]+/i.test(proj.id) || /-mw3[a-z0-9]+/i.test(proj.slug)) {
    issues.push(`Project #${idx} "${title}" contains autogenerated test ID pattern.`);
  }

  // 3. Guard against known test titles
  const forbiddenTitles = ['CASA ENTRE ARBOLES', 'CASA EN EL ILALO', 'PROYECTO ARQUITECTÓNICO SIN TÍTULO'];
  if (forbiddenTitles.includes(title.toUpperCase().trim())) {
    issues.push(`Project #${idx} matches forbidden test title "${title}".`);
  }
});

if (issues.length > 0) {
  console.error('\n🚨 [SENTINEL REJECTED BUILD] Content anomalies detected in projects.json:');
  issues.forEach(iss => console.error(`  - ${iss}`));
  console.error('\nAborting build to protect production integrity. Please resolve the data above.\n');
  process.exit(1);
}

console.log(`✅ [SENTINEL PASSED] All ${projects.length} catalog projects verified authentic and published.\n`);
